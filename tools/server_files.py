def write(mission_dir: Path, server_dir: Path) -> None:
    for p in spawn_gear():
        (mission_dir / f"aotearoa_spawngear_{p['name'].lower()}.json").write_text(json.dumps(p, indent=4) + "\n")
    (mission_dir / "db").mkdir(exist_ok=True)
    (mission_dir / "db" / "messages.xml").write_text(MESSAGES, encoding="utf-8")
    server_dir.mkdir(parents=True, exist_ok=True)
    (server_dir / "start_server.bat").write_text(START_BAT, newline="\r\n")
    sh = server_dir / "start_server.sh"
    sh.write_text(START_SH, newline="\n")
    sh.chmod(0o755)
    (server_dir / "ban.txt").write_text(LIST_HEADER.format(what="Banned players"), newline="\r\n")
    (server_dir / "whitelist.txt").write_text(LIST_HEADER.format(what="Whitelisted players (enableWhitelist = 1 in serverDZ.cfg)"),
                                              newline="\r\n")
    (server_dir / "battleye").mkdir(exist_ok=True)
    (server_dir / "battleye" / "BEServer_x64.cfg").write_text(BE_CFG, newline="\r\n")


def preset_files() -> list[str]:
    return [f"aotearoa_spawngear_{name.lower()}.json" for name in PRESETS]

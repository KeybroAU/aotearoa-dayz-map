def _attrs(lo=0.55, hi=0.9, qmin=0.0, qmax=0.0):
    return {"healthMin": lo, "healthMax": hi, "quantityMin": qmin, "quantityMax": qmax}


def _item(cls, quick=-1, simple=()):
    return {"itemType": cls, "spawnWeight": 1, "attributes": _attrs(), "quickBarSlot": quick,
            "complexChildrenTypes": [], "simpleChildrenTypes": list(simple),
            "simpleChildrenUseDefaultAttributes": True}


def spawn_gear() -> list[dict]:
    presets = []
    for name, p in PRESETS.items():
        slots = []
        for slot in ("Body", "Legs", "Feet", "Headgear"):
            items = [_item(c) for c in p[slot] if c]
            if "" in p[slot]:
                items.append(_item(""))
            slots.append({"slotName": slot, "discreteItemSets": items})
        cargo = [{"itemType": cls, "spawnWeight": 1, "attributes": _attrs(0.7, 1.0, float(q), float(q)),
                  "quickBarSlot": i if cls == "Rag" else -1, "simpleChildrenUseDefaultAttributes": False}
                 for i, (cls, q) in enumerate(CARGO)]
        presets.append({
            "spawnWeight": p["weight"],
            "name": name,
            "characterTypes": CHARACTERS,
            "attachmentSlotItemSets": slots,
            "discreteUnsortedItemSets": [{
                "name": "Cargo", "spawnWeight": 1, "attributes": _attrs(),
                "complexChildrenTypes": cargo, "simpleChildrenUseDefaultAttributes": False,
                "simpleChildrenTypes": [],
            }],
        })
    return presets



"""Performance and balance report: object density, loot spread, vehicle spread and infected.

Reads the generated world and mission and writes docs/BALANCE_REPORT.md and preview/balance_2048.png
(object density as heat, vehicle spawns as dots, the largest areas with no vehicle as rings).

    python balance_report.py
"""

from __future__ import annotations

import csv
import json
import math
import xml.etree.ElementTree as ET
from collections import Counter
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw
from scipy import ndimage
from scipy.spatial import cKDTree

import pack_mod

MAP_DIR = Path(__file__).resolve().parents[1]
SOURCE = MAP_DIR / "source"
MISSION = MAP_DIR / "mission" / "dayzOffline.aotearoa"

CELL_M = 250.0
# Objects per 250 m cell. Vanilla Chernarus forest reaches about 1,500 per cell; past that, view
# distance and server load suffer.
HEAVY_CELL = 1500
VEHICLE_GAP_WARN_M = 2500.0  # land further than this from any vehicle spawn
NETWORK_SPAWNED_WARN = 3000  # object spawner objects are created at server start and sent to every client


def load():
    meta = json.loads((SOURCE / "heightmap.json").read_text())
    raw = np.asarray(Image.open(SOURCE / "heightmap_4096.png")).astype(np.float32)
    h = meta["png_black_m"] + raw / 65535.0 * (meta["png_white_m"] - meta["png_black_m"])
    with (SOURCE / "towns.csv").open(encoding="utf-8") as f:
        towns = list(csv.DictReader(f))
    return meta, h, towns


def tb_objects(meta) -> dict[str, np.ndarray]:
    out = {}
    for f in sorted((SOURCE / "objects").glob("*_tb.txt")):
        pts = []
        for line in f.read_text(encoding="utf-8").splitlines():
            p = line.split(";")
            if len(p) > 2:
                pts.append((float(p[1]) - meta["easting"], float(p[2]) - meta["northing"]))
        out[f.stem.removesuffix("_tb")] = np.array(pts).reshape(-1, 2)
    return out


def nearest_town(towns, x, y) -> str:
    t = min((t for t in towns if t["tier"] != "hamlet"), key=lambda t: math.hypot(x - float(t["x"]), y - float(t["y"])))
    d = math.hypot(x - float(t["x"]), y - float(t["y"]))
    return t["name"] if d < float(t["radius"]) + 200 else f"{d / 1000:.1f} km from {t['name']}"


def main() -> None:
    meta, h, towns = load()
    size = meta["terrain_size_m"]
    land = h > 0.0
    n = int(size // CELL_M)
    lines = ["# Balance and performance report", "",
             "Generated by `tools/balance_report.py` from the current world and mission. Rerun it after changing "
             "the generator.", ""]

    # World objects.
    objs = tb_objects(meta)
    total = sum(len(v) for v in objs.values())
    dens = np.zeros((n, n), dtype=np.int32)
    for pts in objs.values():
        if len(pts):
            c = np.clip((pts[:, 0] // CELL_M).astype(int), 0, n - 1)
            r = np.clip(((size - pts[:, 1]) // CELL_M).astype(int), 0, n - 1)
            np.add.at(dens, (r, c), 1)
    land_cells = ndimage.zoom(land.astype(np.float32), n / land.shape[0], order=0) > 0.5
    spawned = {}
    for f in sorted(MISSION.glob("aotearoa/*_spawner.json")):
        spawned[f.name] = len(json.loads(f.read_text(encoding="utf-8"))["Objects"])
    lines += ["## World objects", "",
              f"{total:,} Terrain Builder objects, {total / (land.sum() * meta['cell_size_m'] ** 2 / 1e6):,.0f} per km² "
              "of land.", "", "| Layer | Objects |", "|---|---|"]
    lines += [f"| {k} | {len(v):,} |" for k, v in sorted(objs.items(), key=lambda kv: -len(kv[1]))]
    lines += ["", f"Busiest {CELL_M:.0f} m cells (limit {HEAVY_CELL:,}):", "", "| Objects | Where |", "|---|---|"]
    order = np.argsort(dens.ravel())[::-1][:6]
    for i in order:
        r, c = divmod(int(i), n)
        lines.append(f"| {dens[r, c]:,} | {nearest_town(towns, (c + 0.5) * CELL_M, size - (r + 0.5) * CELL_M)} |")
    heavy = int((dens > HEAVY_CELL).sum())
    lines += ["", f"{heavy} cells over the limit; median land cell {int(np.median(dens[land_cells])):,} objects.", "",
              "Object spawner files (created at server start, sent to every client):", "", "| File | Objects |",
              "|---|---|"]
    lines += [f"| {k} | {v:,} |" for k, v in spawned.items()]
    lines += ["", f"Total {sum(spawned.values()):,} (warn above {NETWORK_SPAWNED_WARN:,}).", ""]

    # Loot.
    tiers = json.loads((MISSION / "loot_tiers.json").read_text(encoding="utf-8"))
    groups = [(g.get("name"), *map(float, g.get("pos").split()[::2]))
              for g in ET.parse(MISSION / "mapgrouppos.xml").getroot().iter("group")]
    tier_of_town = tiers.get("towns", {})
    by_tier = Counter()
    by_town = Counter()
    T = [t for t in towns]
    tree = cKDTree([(float(t["x"]), float(t["y"])) for t in T])
    for name, x, y in groups:
        d, i = tree.query((x, y))
        t = T[i]
        if d < float(t["radius"]) + 60:
            by_town[t["name"]] += 1
            by_tier[tier_of_town.get(t["name"], 0)] += 1
        else:
            by_tier["sites"] += 1
    density, points, vanilla_points = pack_mod.loot_density()
    lines += ["## Loot", "", f"{len(groups):,} loot buildings with {points:,} loot points, {density:.0%} of "
              f"Chernarus's {vanilla_points:,}. `pack.bat` scales loot by {min(1.0, max(0.3, density)):.2f} so each "
              "building holds about as much as on Chernarus (`--vanilla-loot` turns this off).", "",
              "| Loot tier | Buildings |", "|---|---|"]
    lines += [f"| {k} | {v:,} |" for k, v in sorted(by_tier.items(), key=lambda kv: str(kv[0]))]
    lines += ["", "Most loot buildings:", "", "| Town | Buildings | Tier |", "|---|---|---|"]
    lines += [f"| {k} | {v} | {tier_of_town.get(k, '?')} |" for k, v in by_town.most_common(8)]
    lines.append("")

    # Vehicles.
    ev = ET.parse(MISSION / "cfgeventspawns.xml").getroot()
    veh = {e.get("name"): [(float(p.get("x")), float(p.get("z"))) for p in e.iter("pos")]
           for e in ev.iter("event") if e.get("name").startswith("Vehicle")}
    allv = np.array([p for pts in veh.values() for p in pts])
    vt = cKDTree(allv)
    rr, cc = np.nonzero(land[::16, ::16])
    samples = np.column_stack([(cc * 16 + 0.5) * meta["cell_size_m"], size - (rr * 16 + 0.5) * meta["cell_size_m"]])
    gap, _ = vt.query(samples)
    lines += ["## Vehicles", "", "| Event | Spawn positions |", "|---|---|"]
    lines += [f"| {k} | {len(v)} |" for k, v in sorted(veh.items())]
    lines += ["", f"Distance from any land to the nearest vehicle spawn: median {np.median(gap):,.0f} m, "
              f"95th percentile {np.percentile(gap, 95):,.0f} m, worst {gap.max():,.0f} m. "
              f"{(gap > VEHICLE_GAP_WARN_M).mean() * 100:.1f}% of land is over {VEHICLE_GAP_WARN_M:,.0f} m away.", ""]
    worst = []
    for i in np.argsort(gap)[::-1]:
        x, y = samples[i]
        if all(math.hypot(x - a, y - b) > 3000 for a, b, _ in worst):
            worst.append((x, y, gap[i]))
        if len(worst) == 5:
            break
    lines += ["Largest areas without a vehicle:", "", "| Gap | Where |", "|---|---|"]
    lines += [f"| {d:,.0f} m | {nearest_town(towns, x, y)} |" for x, y, d in worst]
    lines.append("")

    # Infected.
    zt = ET.parse(MISSION / "env" / "zombie_territories.xml").getroot()
    zones = Counter()
    for terr in zt.iter("territory"):
        for z in terr.iter("zone"):
            zones[z.get("name")] += 1
    lines += ["## Infected", "", f"{sum(zones.values())} infected zones.", "", "| Zone type | Zones |", "|---|---|"]
    lines += [f"| {k} | {v} |" for k, v in zones.most_common()]
    lines.append("")

    warnings = []
    if heavy:
        warnings.append(f"{heavy} cells have more than {HEAVY_CELL:,} objects.")
    if sum(spawned.values()) > NETWORK_SPAWNED_WARN:
        warnings.append(f"{sum(spawned.values()):,} spawner objects is a lot to send at login.")
    if (gap > VEHICLE_GAP_WARN_M).mean() > 0.05:
        warnings.append(f"{(gap > VEHICLE_GAP_WARN_M).mean() * 100:.0f}% of land is over {VEHICLE_GAP_WARN_M:,.0f} m from a vehicle.")
    lines += ["## Summary", ""] + ([f"- {w}" for w in warnings] or ["- Nothing over the limits."]) + [""]
    (MAP_DIR / "docs" / "BALANCE_REPORT.md").write_text("\n".join(lines), encoding="utf-8")

    heat = np.clip(dens / HEAVY_CELL, 0, 1)
    base = np.asarray(Image.open(MAP_DIR / "preview" / "satellite_2048.png").convert("L").resize((2048, 2048)),
                      dtype=np.float32) / 255.0
    hz = np.asarray(Image.fromarray((heat * 255).astype(np.uint8)).resize((2048, 2048), Image.BILINEAR),
                    dtype=np.float32) / 255.0
    rgb = np.stack([base * 0.6 + hz * 0.9, base * 0.6 + hz * 0.25, base * 0.6], -1)
    img = Image.fromarray((np.clip(rgb, 0, 1) * 255).astype(np.uint8))
    d = ImageDraw.Draw(img)
    k = 2048 / size
    for x, y in allv:
        d.ellipse([x * k - 2, (size - y) * k - 2, x * k + 2, (size - y) * k + 2], fill=(80, 200, 255))
    for x, y, gd in worst:
        r = gd * k
        d.ellipse([x * k - r, (size - y) * k - r, x * k + r, (size - y) * k + r], outline=(255, 255, 0), width=2)
    img.save(MAP_DIR / "preview" / "balance_2048.png", optimize=True)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
